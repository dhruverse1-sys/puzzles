G = """7v 5> 2> 8v 3v 1> 5v 7< 4v 1<
2> 4> 1^ 3* 5> 5v 6v 6v 2< 1v
3v 6> 3> 1> 4v 7v 6v 1^ 8< 3<
3> 5> 5> 3^ 5> 2v 1< 3v 2^ 1v
1^ 6> 3> 3v 1< 4^ 1* 4^ 2v 9<
2> 3^ 3^ 3^ 4^ 3v 2> 4v 4^ 6<
5^ 5^ 4> 3v 3< 5< 3< 2> 6< 6^
2> 4^ 3^ 5> 2^ 4< 2v 2< 5^ 4<
1v 4^ 2* 4> 4^ 4> 2< 3^ 4* 8<
9> 4^ 6^ 2< 2^ 3< 6< 1> 4< 4^"""
cells = [row.split() for row in G.splitlines()]
D = {'^': (-1, 0), 'v': (1, 0), '<': (0, -1), '>': (0, 1)}
def succ(r, c):
    t = cells[r][c]; n = int(t[0]); d = t[1]
    if d == '*': return None
    dr, dc = D[d]; return (r + dr * n, c + dc * n)
